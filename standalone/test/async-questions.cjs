const assert=require('node:assert/strict');
const {questions,buildReply,hasReply,displayReply}=require('../runtime/async-questions.cjs');
const item={type:'agentMessage',id:'call_fixture',questions:[{title:'Choose a connection',options:['Local (Recommended)','Remote']},{title:'Project details'}]};
assert.equal(questions(item).length,2);
const reply=buildReply(item,{'0':'Local (Recommended)','1':'Keep <this> project'});
const content=JSON.parse(reply.split('\n')[1]);
assert.deepEqual(JSON.parse(content[0].questionItemId),['request_user_input_async','call_fixture',0]);
assert.equal(content[1].answer,'Keep <this> project');
assert.equal(displayReply(reply),'Choose a connection\nLocal (Recommended)\n\nProject details\nKeep <this> project');
assert.equal(displayReply('ordinary message'),null);
assert.equal(hasReply([{type:'userMessage',content:[{type:'text',text:reply}]}],item.id),true);
assert.equal(hasReply([{type:'userMessage',text:reply}],'different'),false);
assert.equal(hasReply([{type:'userMessage',text:'<send_user_message_question_reply>invalid</send_user_message_question_reply>'}],item.id),false);
assert.throws(()=>buildReply(item,{'0':'Local'}));
assert.throws(()=>buildReply(item,{'0':'Local','1':'x'.repeat(20001)}));
assert.deepEqual(questions({...item,questions:[{title:'Invalid',options:[{}]}]}),[]);
const records=require('../runtime/question-records.cjs');
const skipped=buildReply(item,undefined,{skip:true});
assert.ok(JSON.parse(skipped.split('\n')[1]).every(reply=>reply.answer===records.SKIPPED));
assert.ok(!displayReply(skipped).includes(records.SKIPPED));
const legacy={items:[item,{type:'userMessage',content:[{type:'text',text:reply}]}]};
records.restore(legacy);
assert.equal(legacy.questionHistory[0].answers['1'],'Keep <this> project');
assert.equal(legacy.asyncQuestionReplies[item.id],'sent');
records.restore(legacy);assert.equal(legacy.questionHistory.length,1);
const secretSession={};records.remember(secretSession,{id:'b:secret',origin:'blocking',questions:[{id:'secret',question:'Private',isSecret:true}],answers:{secret:'fixture-private-answer'}});
assert.equal(JSON.stringify(secretSession).includes('fixture-private-answer'),false);
for(let i=0;i<105;i++)records.remember(secretSession,{id:'b:'+i,origin:'blocking',questions:[{id:'q',question:'Question'}],answers:{q:'Answer'}});
assert.equal(secretSession.questionHistory.length,100);
console.log('Async questions: structured CLI metadata, correlated replies, validation and historical reply matching passed.');
